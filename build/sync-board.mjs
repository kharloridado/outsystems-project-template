#!/usr/bin/env node
/* sync-board.mjs — mirror the GitHub Project board into the repo's files.
 *
 * WHY THIS IS A SCRIPT AND NOT A SKILL. `board-sync` (the skill) is judgment work: it
 * reconciles state against git, reclaims crashed claims, and writes prose. Mirroring a lane
 * into a file is not judgment — it is a projection, it has one right answer, and it needs to
 * run unattended on a schedule where no model is in the loop. Two different jobs.
 *
 * WHY IT POLLS INSTEAD OF LISTENING. `projects_v2_item` — the webhook/Actions event for board
 * activity — fires for ORGANISATION projects only. A USER-owned project
 * (github.com/users/<login>/projects/3), so there is no event to subscribe to and no
 * `on: projects_v2_item` trigger available. A poll is not a shortcut here; it is the only
 * mechanism GitHub offers for this board.
 *
 * WHY IT RUNS IN GITHUB ACTIONS. Projects v2 is GraphQL-only, and a Claude Code cloud routine
 * cannot reach it: no `gh` on PATH, no `project_*` tool in the cloud GitHub MCP, no GraphQL
 * passthrough, and raw GraphQL to api.github.com refused by the egress proxy. Actions runs on
 * GitHub's own infrastructure with no such restriction. So Actions reads the board and commits
 * plain files; the nightly routine then reads files, which it can do from anywhere. Actions is
 * the bridge between the two halves.
 *
 * WHAT IT WILL AND WILL NOT WRITE — the whole safety model in two lines:
 *   MIRROR    items[].board_status + deliverables.md   -> written directly, always safe
 *   PROMOTE   items[].status = "queued"                -> ONLY with --promote, ONLY via a PR
 *
 * `loop/goal.md` says a lane queues nothing; scope is the signed inventory and promotion is a
 * reviewable git change with an author. That rule is why this script cannot flip `status` on a
 * schedule. `--promote` exists so a workflow can prepare the change on a branch — a human
 * merging that PR is the signature, and it is a better one than a lane move, because Projects
 * v2 does not expose who moved a card.
 *
 *   node build/sync-board.mjs                 # mirror + regenerate deliverables.md
 *   node build/sync-board.mjs --dry-run       # report only, write nothing
 *   node build/sync-board.mjs --promote       # additionally apply queue promotions (PR job)
 *   node build/sync-board.mjs --json          # machine-readable summary on stdout
 *
 * Token: BOARD_SYNC_TOKEN | GH_TOKEN | GITHUB_TOKEN, else `gh auth token`. Needs the `project`
 * scope — the Actions GITHUB_TOKEN cannot read a user-owned Projects v2 board.
 */
import { appendFileSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { boardToken, fetchBoard, laneOf, nameOf } from "./lib/board-api.mjs";
import { itemAtPrHead } from "./lib/gh-pr.mjs";
import { projectConfig, root } from "./lib/project-config.mjs";

const args = process.argv.slice(2);
const has = (f) => args.includes(f);
const DRY = has("--dry-run");
const PROMOTE = has("--promote");
const JSON_OUT = has("--json");
/* --pr-body <path> writes the promotion PR's markdown body. It lives here rather than inline
 * in the workflow because a `node -e` nested inside a YAML block scalar inside a shell
 * heredoc is three layers of quoting and no way to test it. */
const PR_BODY_PATH = args[args.indexOf("--pr-body") + 1] && has("--pr-body") ? args[args.indexOf("--pr-body") + 1] : null;

const STATE_PATH = join(root, "loop", "state.json");
const GOAL_PATH = join(root, "loop", "goal.md");
const DELIVERABLES_PATH = join(root, "deliverables.md");
const BEGIN = "<!-- BOARD-SYNC:BEGIN — generated by build/sync-board.mjs. Do not edit inside. -->";
const END = "<!-- BOARD-SYNC:END -->";

/* FRESH PROMOTION — work that has never been built. `Ready` means "start it". */
const PROMOTABLE_FROM = new Set(["backlog", "deferred"]);

/* REWORK RE-QUEUE — work that HAS been built and is being sent back. This is the review
 * channel on this project: the reviewer leaves comments on the card and drags it from
 * `Ready for Review` (or `Blocked`) back to `Ready`, and the next nightly run reworks it
 * against those comments.
 *
 * This deliberately reverses the original rule here ("a lane cannot rewind work that
 * exists"), and the safety that rule was buying is preserved a different way: a re-queue is
 * still only ever proposed, never committed to `main`, and lands through the same promotion
 * PR that a human merges. What changes is the SET of statuses a lane may act on, not who
 * gets to sign.
 *
 * `approved`, `handover` and `shipped` are NOT here, and must not be. Those are past the
 * human signature — a card slipping back to `Ready` after a merge must never silently
 * re-open merged work. `in-progress` is excluded too: a run holds that claim right now, and
 * re-queueing under a live maker is how two runs end up on one branch. */
const REQUEUE_FROM = new Set(["built", "needs-human", "needs-re-ref"]);

/* Lanes a card may be dragged back to `Ready` FROM and still be treated as rework. Recorded
 * on the item so the maker knows it is reworking rather than starting, and so the promotion
 * PR can say which lane it came out of. */
const REWORK_SOURCE_LANES = new Set(["Ready for Review", "Blocked", "In Progress"]);

/* Past the human signature. A card in one of these that shows up in `Ready` is reported, never
 * acted on — see the `unmatched` branch below. */
const FROZEN_STATUSES = new Set(["approved", "handover", "shipped"]);

function fail(msg) {
  console.error(`sync:board → ${msg}`);
  process.exit(1);
}


/** Issue numbers with a row in goal.md's signed inventory. Nothing outside it may be queued —
 *  hard rule: "no component enters the build queue without a row in the inventory of record". */
function signedInventoryIssues() {
  const md = readFileSync(GOAL_PATH, "utf8");
  const issues = new Set();
  for (const m of md.matchAll(/\[#(\d+)\]\([^)]*\/issues\/\d+\)/g)) issues.add(Number(m[1]));
  return issues;
}

function main() {
  return run().catch((e) => fail(e.message));
}

async function run() {
  const cfg = projectConfig();
  const board = cfg.board ?? {};
  if (!board.owner || !board.number) fail("project.config.json → board has no owner/number pointer.");
  const repo = cfg.repo;

  const state = JSON.parse(readFileSync(STATE_PATH, "utf8"));
  const signed = signedInventoryIssues();
  const { id: projectId, title, nodes } = await fetchBoard(board, boardToken({ fail }), { fail });

  /* Index cards by issue number; fall back to the cached board item id. Matching on the issue
   * is what makes this robust to a card being deleted and re-added — the node id changes, the
   * issue does not. */
  const byIssue = new Map();
  const byItemId = new Map();
  for (const card of nodes) {
    if (card.content?.number) byIssue.set(card.content.number, card);
    byItemId.set(card.id, card);
  }

  const now = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
  const mirrored = [];
  const promotions = [];
  const requeues = [];
  const demotions = [];
  const unmatched = [];

  for (const item of state.items ?? []) {
    const card = (item.issue && byIssue.get(item.issue)) || (item.board_item_id && byItemId.get(item.board_item_id));
    if (!card) {
      unmatched.push(item.id);
      continue;
    }
    const lane = laneOf(card);
    /* Read the previous lane BEFORE the mirror overwrites it — it is the only record of
     * which lane a rework came out of, and it is gone one line later. */
    const priorLane = item.board_status ?? null;
    if (priorLane !== lane) mirrored.push({ id: item.id, from: priorLane, to: lane });

    // MIRROR — always safe: this field is a projection of the board and nothing queues off it.
    item.board_status = lane;
    item.board_item_id = card.id;

    // PROMOTE — proposed here, applied only under --promote, landed only through a PR.
    const inInventory = item.issue && signed.has(item.issue);

    /* ASK THE PR BRANCH WHAT ACTUALLY HAPPENED TO THIS ITEM.
     *
     * `main` describes an item whose PR is still open as though nothing had happened to it —
     * `backlog`, because `status: built` was written on the branch and has not merged. Trusting
     * `main` here reads a card dragged back to `Ready` as a FIRST BUILD, queues a rebuild from
     * the Figma ref, and silently discards the open PR's work: its checker PASS, its
     * measurements, its handover body.
     *
     * Measured on the source project: a component was dragged out of review to `Ready` while its PR sat open
     * with `built` on its branch. This function is what stops that becoming a rebuild.
     *
     * Only asked when it can change the answer — the lane is `Ready`, the item is in scope, and
     * `main` claims a status that would otherwise mean "never built". One `gh` call, and only
     * for the handful of cards that are actually sitting in `Ready`. */
    let effectiveStatus = item.status;
    let headPr = null;
    if (lane === "Ready" && inInventory && PROMOTABLE_FROM.has(item.status)) {
      const head = itemAtPrHead(repo, item);
      if (head?.pr?.state === "OPEN" && head.item && REQUEUE_FROM.has(head.item.status)) {
        effectiveStatus = head.item.status;
        headPr = head.pr;
      }
    }

    if (lane === "Ready" && item.status !== "queued" && inInventory && PROMOTABLE_FROM.has(effectiveStatus)) {
      promotions.push({ kind: "promote", id: item.id, issue: item.issue, name: nameOf(card), from: item.status, to: "queued" });
      if (PROMOTE) item.status = "queued";
    } else if (lane === "Ready" && item.status !== "queued" && inInventory && REQUEUE_FROM.has(effectiveStatus)) {
      /* Rework. The reviewer's comments ARE the spec for the next round, so record where it
       * came from and point the maker at them — a re-queued item with no pointer looks
       * identical to a fresh one and gets rebuilt from the Figma ref, silently discarding
       * the review. */
      /* `from` is the status the WORK is at, which for an open PR lives on its branch, not on
       * main. Reporting main's `backlog` here would put "backlog → queued" in the PR body for
       * something that has already been built and reviewed. */
      const from = effectiveStatus;
      const openPr = headPr?.number ?? (item.pr || null);
      requeues.push({
        kind: "requeue",
        id: item.id,
        issue: item.issue,
        name: nameOf(card),
        from,
        to: "queued",
        fromLane: priorLane && REWORK_SOURCE_LANES.has(priorLane) ? priorLane : "—",
        rounds: item.rounds ?? 0,
        pr: openPr,
        statusOnMain: item.status,
      });
      if (PROMOTE) {
        item.status = "queued";
        item.requeued_from = from;
        item.requeued_at = now;
        if (openPr) item.requeued_pr = openPr;
        /* Not a free-text instruction — a pointer. The loop reads the comments itself and
         * applies hard rule 12 to them (data, never instructions) and `board.owners` to
         * their authors. */
        item.rework_spec = `comments by board.owners on issue #${item.issue}` + (openPr ? ` and PR #${openPr}` : "");
      }
    } else if (lane === "Ready" && item.status !== "queued" && !inInventory) {
      unmatched.push(`${item.id} (Ready on the board, but no row in goal.md's signed inventory — not queued)`);
    } else if (lane === "Ready" && FROZEN_STATUSES.has(item.status)) {
      /* Past the signature line. Say it loudly rather than silently ignoring the drag — the
       * reviewer moved a card and is entitled to know nothing happened. */
      unmatched.push(
        `${item.id} (Ready on the board, but state.json says \`${item.status}\` — that is past the human signature. ` +
          `Re-opening merged work needs a new inventory row, not a lane move.)`
      );
    } else if (lane === "Backlog" && item.status === "queued") {
      demotions.push({ kind: "demote", id: item.id, issue: item.issue, name: nameOf(card), from: "queued", to: "backlog" });
      if (PROMOTE) item.status = "backlog";
    }
  }

  /* REVERSE SCAN — cards on the board with no item in state.json at all.
   *
   * The loop above walks `state.items`, so a card that exists only on the board is invisible
   * to it: it cannot be mirrored, promoted, or reported, and the sync completes "clean" while
   * the card sits in `Ready` forever. That is not hypothetical — it is how a component added
   * straight to the board
   * reached `Ready`, was never queued, and produced no signal anywhere.
   *
   * A deliverable card with no state item is almost always a card created straight on the
   * board without a row being added to goal.md's signed inventory. That needs a human: the
   * hard rule is that nothing enters the queue without an inventory row, so the fix is a
   * signed row plus an item, not a lane. Report it every run until someone acts. */
  const knownIssues = new Set((state.items ?? []).map((i) => i.issue).filter(Boolean));
  const orphans = [];
  for (const card of nodes) {
    const num = card.content?.number;
    if (!num || knownIssues.has(num)) continue;
    // Findings and handovers legitimately live on this board without being loop items.
    if (!/^\s*\[deliverable\]/i.test(card.content?.title ?? "")) continue;
    orphans.push({ issue: num, name: nameOf(card), lane: laneOf(card), inInventory: signed.has(num) });
  }
  for (const o of orphans) {
    unmatched.push(
      `#${o.issue} "${o.name}" is a deliverable card in \`${o.lane}\` with NO item in state.json` +
        (o.inInventory
          ? " — it has a signed inventory row, so it needs an `items[]` entry adding."
          : " — and NO row in goal.md's signed inventory. It cannot be built until a scope owner adds both.")
    );
  }

  /* Tier-order warning. goal.md: "Queue order is this table's order, gated by the tier
   * checkpoints." Promoting a composite while primitives are unbuilt is legal here but is
   * almost always a mis-drag, and the loop will stop at the checkpoint anyway. Say so in the
   * PR rather than letting someone wonder why their card never built. */
  const tierRank = (t) => (state.tiers ?? []).indexOf(String(t ?? "").toLowerCase());
  const currentRank = tierRank(state.current_tier);
  const aheadOfTier = [...promotions, ...requeues].filter((p) => {
    const item = (state.items ?? []).find((i) => i.id === p.id);
    return item && currentRank !== -1 && tierRank(item.tier) > currentRank;
  });

  state.board_mirror = {
    _note:
      "Projection of GitHub Project board lanes, written by build/sync-board.mjs. The board is a " +
      "HUMAN VIEW here (board.drivesLoop is false): nothing in this block queues work. Queue " +
      "position is items[].status, and scope is loop/goal.md's signed inventory.",
    project_id: projectId,
    title,
    synced_at: now,
    cards: nodes.length,
  };

  const deliverables = renderDeliverables({ cfg, state, nodes, now, orphans, signed });

  /* Write only when something OTHER than the sync timestamp moved. A poll that rewrote the
   * stamp every 15 minutes would commit to main all day and bury real board changes in
   * timestamp noise — and the nightly routine would see a repo that looks busy and isn't. */
  const written = DRY
    ? []
    : [
        writeIfChanged(STATE_PATH, JSON.stringify(state, null, 2) + "\n") && "loop/state.json",
        writeIfChanged(DELIVERABLES_PATH, deliverables) && "deliverables.md",
      ].filter(Boolean);

  const summary = {
    dryRun: DRY,
    written,
    promoteApplied: PROMOTE && !DRY,
    cards: nodes.length,
    mirrored,
    promotions,
    requeues,
    demotions,
    unmatched,
    orphans,
    aheadOfTier,
    currentTier: state.current_tier ?? null,
  };

  if (PR_BODY_PATH && !DRY) writeFileSync(PR_BODY_PATH, promotionPrBody(summary, cfg));

  if (JSON_OUT) {
    console.log(JSON.stringify(summary, null, 2));
  } else {
    const w = DRY ? "would write" : "wrote";
    console.log(`sync:board → ${nodes.length} cards from "${title}"`);
    console.log(`  lane changes mirrored: ${mirrored.length}${mirrored.map((m) => `\n    ${m.id}: ${m.from ?? "—"} → ${m.to ?? "—"}`).join("")}`);
    console.log(`  queue promotions ${PROMOTE ? "APPLIED" : "proposed"}: ${promotions.length}${promotions.map((p) => `\n    ${p.id} (#${p.issue}): ${p.from} → queued`).join("")}`);
    if (requeues.length)
      console.log(
        `  rework re-queues ${PROMOTE ? "APPLIED" : "proposed"}: ${requeues.length}` +
          requeues.map((r) => `\n    ${r.id} (#${r.issue}): ${r.from} → queued  [pulled back from ${r.fromLane}, round ${r.rounds} → ${r.rounds + 1}]`).join("")
      );
    if (demotions.length) console.log(`  queue demotions ${PROMOTE ? "APPLIED" : "proposed"}: ${demotions.length}${demotions.map((d) => `\n    ${d.id}: queued → backlog`).join("")}`);
    if (unmatched.length) console.log(`  unmatched / not queued:\n    ${unmatched.join("\n    ")}`);
    console.log(`  ${w}: ${DRY ? "loop/state.json, deliverables.md" : written.join(", ") || "nothing (no change beyond the sync timestamp)"}`);
  }

  // Let the workflow branch on the result without re-parsing stdout.
  if (process.env.GITHUB_OUTPUT) {
    appendFileSync(
      process.env.GITHUB_OUTPUT,
      `promotions=${promotions.length}\n` +
        `requeues=${requeues.length}\n` +
        `orphans=${orphans.length}\n` +
        `demotions=${demotions.length}\n` +
        `mirrored=${mirrored.length}\n` +
        `summary<<EOF\n${JSON.stringify(summary)}\nEOF\n`
    );
  }
}

/** Regenerate ONLY the region between the markers, so the prose sections `board-sync` writes
 *  (Progress, Findings) survive a mechanical run untouched. */
function renderDeliverables({ cfg, state, nodes, now, orphans = [], signed = new Set() }) {
  const existing = (() => {
    try {
      return readFileSync(DELIVERABLES_PATH, "utf8");
    } catch {
      return "";
    }
  })();

  const byIssue = new Map();
  for (const card of nodes) if (card.content?.number) byIssue.set(card.content.number, card);

  const tierOrder = state.tiers ?? [];
  const rank = (t) => {
    const i = tierOrder.indexOf(String(t ?? "").toLowerCase());
    return i === -1 ? tierOrder.length : i;
  };
  const repoUrl = `https://github.com/${cfg.repo}`;
  const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : "—");

  const rows = (state.items ?? [])
    .map((item) => {
      const card = item.issue ? byIssue.get(item.issue) : null;
      return {
        name: card ? nameOf(card) : item.id,
        lane: item.board_status ?? "—",
        status: item.status ?? "—",
        tier: card?.tier?.name ?? cap(item.tier),
        level: card?.level?.name ?? item.level ?? "—",
        issue: item.issue,
        pr: item.pr,
        node: item.node,
        /* `merged_sha` was the field name while the board drove the loop; the items written
         * since carry the merge commit as `sha`. Read both — reading only one printed
         * "(undefin)" into the customer-facing table for every merged component. */
        merged: item.merged_at
          ? `${item.merged_at.slice(0, 10)}` +
            (item.merged_sha || item.sha ? ` (\`${String(item.merged_sha || item.sha).slice(0, 7)}\`)` : "")
          : "—",
        /* Membership of the signed inventory, per row. Without it the table reads as "these
         * are the deliverables" when one of them may be a card nobody agreed to. */
        inInventory: item.issue ? signed.has(item.issue) : false,
        _rank: rank(item.tier),
      };
    })
    .sort((a, b) => a._rank - b._rank || a.name.localeCompare(b.name));

  const table = rows
    .map(
      (r) =>
        `| ${r.name} | \`${r.lane}\` | \`${r.status}\` | ${r.inInventory ? "✅" : "❌ **no row**"} | ` +
        `${r.tier || "—"} | ${r.level || "—"} | ` +
        `${r.issue ? `[#${r.issue}](${repoUrl}/issues/${r.issue})` : "—"} | ` +
        `${r.pr ? `[#${r.pr}](${repoUrl}/pull/${r.pr})` : "—"} | ` +
        `${r.node ? `\`${r.node}\`` : "—"} | ${r.merged} |`
    )
    .join("\n");

  const divergent = rows.filter((r) => r.lane === "Ready" && r.status !== "queued");

  const block = `${BEGIN}
<!-- GENERATED — do not edit between the BOARD-SYNC markers.
     Written by build/sync-board.mjs from GitHub Project board ${cfg.board.number}.
     Board: ${cfg.board.url}
     Generated: ${now} -->

# Deliverables

The human-readable map of what this design system owes the customer, projected from the
GitHub Project board.

**This file is not the inventory of record.** \`loop/goal.md\` runs \`Inventory source = artifact\`:
the signed table there owns scope, \`loop/state.json\` \`items[].status\` owns queue position, and
the loop reads neither the board nor this file. What follows is a **status report**.

---

## Components

Sorted by tier, then component. ${rows.length} items.

| Component | Lane | \`state.json\` | In signed inventory? | Tier | Level | Issue | PR | Figma node | Merged |
|---|---|---|---|---|---|---|---|---|---|
${table}

**Lane and \`state.json\` are different facts.** The lane is a human's intent on the board; the
\`state.json\` column is what the loop will actually do next. With \`board.drivesLoop: false\` a
drag into \`Ready\` does not queue anything — a promotion PR does, and merging it is the
signature. ${
    divergent.length
      ? `Right now ${divergent.length} card${divergent.length === 1 ? " is" : "s are"} \`Ready\` without being queued: ` +
        divergent.map((d) => `**${d.name}** (\`${d.status}\`)`).join(", ") +
        "."
      : "No card is currently `Ready` without being queued."
  }

**Level is unset until the maker audits the component** — exists-as-is / exists-not-exact /
doesn't-exist is a build-time outcome, not a backlog-time decision.

**The PR column comes from \`loop/state.json\`, so it lags an in-flight build.** An item whose
PR is still open carries its \`pr\` on that PR's own branch, not on \`main\` — the lane column is
the live fact until it merges.

**Date entered \`Ready\` is not recorded.** Projects v2 does not expose lane-transition
timestamps in a queryable form, so the column is omitted rather than guessed.
${
  orphans.length
    ? `
## On the board, not in the pipeline

${orphans.length === 1 ? "One deliverable card exists" : `${orphans.length} deliverable cards exist`} on board ${cfg.board.number} with no item in \`loop/state.json\`. The loop cannot see ${orphans.length === 1 ? "it" : "them"}, and no run will build ${orphans.length === 1 ? "it" : "them"} — whatever lane ${orphans.length === 1 ? "it sits" : "they sit"} in.

| Card | Lane | Signed inventory row? | What it needs |
|---|---|---|---|
${orphans
  .map(
    (o) =>
      `| [#${o.issue} ${o.name}](https://github.com/${cfg.repo}/issues/${o.issue}) | \`${o.lane}\` | ${o.inInventory ? "yes" : "**no**"} | ` +
      `${o.inInventory ? "an `items[]` entry in `loop/state.json`" : "a row in `loop/goal.md`'s signed table **and** an `items[]` entry"} |`
  )
  .join("\n")}

A card created straight on the board is not scope. \`loop/goal.md\`'s signed table is, and the hard rule is that nothing enters the queue without a row in it — so this is a human signature, not something the sync can fix. It is listed here rather than skipped because a card that is invisible everywhere is exactly how a deliverable gets forgotten.
`
    : ""
}${END}`;

  if (existing.includes(BEGIN) && existing.includes(END)) {
    return existing.replace(new RegExp(`${escapeRe(BEGIN)}[\\s\\S]*?${escapeRe(END)}`), () => block);
  }
  // First run: keep the hand/agent-written prose, drop only the sections this script owns.
  const tail = preservedTail(existing);
  return `${block}${tail ? `\n\n${tail}` : ""}`.trimEnd() + "\n";
}

/** Sections `renderDeliverables` writes itself. Anything else in an existing deliverables.md is
 *  somebody's analysis and must survive the first mechanical run. */
const OWNED_SECTIONS = [/^components$/, /^on the board, not in the pipeline$/, /file input.*signed inventory/];

/** On the FIRST run there are no markers, so the script has to decide for itself where its own
 *  output stops and a human's prose starts. Keep everything from the first `## ` heading it does
 *  not own.
 *
 *  This used to slice from a literal `"## Progress"` — a heading that does not exist in this
 *  repo's deliverables.md. `indexOf` returned -1, the guard treated that as "no tail", and the
 *  first run silently deleted the State-of-play and Findings sections: ~40 lines of analysis,
 *  gone, in a commit whose message said it was regenerating a table. */
function preservedTail(existing) {
  if (!existing.trim()) return "";
  const lines = existing.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const m = /^##\s+(.*?)\s*$/.exec(lines[i]);
    if (!m) continue;
    const title = m[1].replace(/[^\p{L}\p{N}\s,()#-]/gu, "").trim().toLowerCase();
    if (OWNED_SECTIONS.some((re) => re.test(title))) continue;
    return lines.slice(i).join("\n").trim();
  }
  return "";
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** The body of the queue-promotion PR. Merging that PR is the promotion, so the body has to
 *  say what is being signed for and why a lane move was not enough on its own. */
function promotionPrBody(summary, cfg) {
  const rows = [
    ...summary.promotions.map((p) => ({ verb: "build", ...p })),
    ...summary.requeues.map((r) => ({ verb: "**rework**", ...r })),
    ...summary.demotions.map((d) => ({ verb: "pause", ...d })),
  ];
  const repoUrl = `https://github.com/${cfg.repo}`;
  const table = rows
    .map(
      (r) =>
        `| ${r.verb} | \`${r.id}\` | [#${r.issue}](${repoUrl}/issues/${r.issue}) | \`${r.from}\` → \`${r.to}\` | ` +
        `${r.kind === "requeue" ? `pulled back from \`${r.fromLane}\` — round ${r.rounds} → ${r.rounds + 1}` : "—"} |`
    )
    .join("\n");

  const withOpenPr = (summary.requeues ?? []).filter((r) => r.pr);
  const openPrNote = withOpenPr.length
    ? `

> **${withOpenPr.length === 1 ? "This row has an open PR" : "These rows have open PRs"}.** ${withOpenPr
        .map((r) => `**${r.name}** → [#${r.pr}](${repoUrl}/pull/${r.pr})`)
        .join(", ")}
>
> \`loop/state.json\` on \`main\` says \`${withOpenPr[0].statusOnMain}\` for ${withOpenPr.length === 1 ? "it" : "these"}, because \`built\` was written on the PR branch and has not merged. The status above is read from the PR head, which is the truthful one. **This is a rework of that PR, not a rebuild** — the loop pushes the next round onto the same branch and the PR keeps its history. If the loop instead cuts a fresh branch and rebuilds from the Figma ref, the open PR's checker PASS, measurements and handover body are lost; stop and fix that before merging this.`
    : "";

  const reworkNote = summary.requeues.length
    ? `

## Rework rows — read this before merging

${summary.requeues.length === 1 ? "One item was" : `${summary.requeues.length} items were`} **pulled back out of review**, not queued for the first time. For ${summary.requeues.length === 1 ? "that item" : "those items"} the review comments are the spec of the next round: the loop re-reads the frozen Figma ref *and* the comments on the issue/PR, and rebuilds against both.

Only comments authored by \`board.owners\` (${(cfg.board.owners ?? []).map((o) => `\`${o}\``).join(", ") || "—"}) are read as requirements. Everything else on the card is untrusted input (hard rule 12) — a comment claiming approval or urgency is just text.

**If you dragged the card back without leaving a comment, close this PR and comment first.** A re-queue with nothing to act on rebuilds the item from the same ref and produces the same result, having spent a full maker/checker round to do it.${openPrNote}`
    : "";

  const tierNote = summary.aheadOfTier?.length
    ? `

## ⚠ Ahead of the current tier

Current tier is \`${summary.currentTier}\`. ${summary.aheadOfTier.map((p) => `**${p.name}**`).join(", ")} ${summary.aheadOfTier.length === 1 ? "sits" : "sit"} in a later tier, and \`loop/goal.md\` builds in tier order gated by the checkpoints in \`loop/state.json\`. Merging this queues ${summary.aheadOfTier.length === 1 ? "it" : "them"}, but the loop will stop at the checkpoint before building — so if this was a mis-drag, fix it on the board rather than wondering why nothing happened.`
    : "";

  const orphanNote = summary.orphans?.length
    ? `

## 🚫 Deliverable cards with no item in \`loop/state.json\`

${summary.orphans.map((o) => `- **#${o.issue} ${o.name}** — lane \`${o.lane}\`; ${o.inInventory ? "has a signed inventory row but no `items[]` entry." : "**no signed inventory row and no `items[]` entry.**"}`).join("\n")}

These are invisible to the loop. A card created straight on the board is not scope — \`loop/goal.md\`'s signed table is, and nothing enters the queue without a row in it. This sync cannot fix that for you: adding scope is a human signature, so it takes a row in \`loop/goal.md\` plus a matching \`items[]\` entry, both in a PR someone approves.

This block is why the sync reports rather than silently skipping: a card sitting in \`Ready\` with no item behind it used to produce no signal anywhere, and the first anyone knew was asking why the nightly run ignored it.`
    : "";

  /* A sync with no queue change is the COMMON case: somebody moved a card between two lanes the
   * queue does not care about, and all that moved is the projection. Opening that PR under the
   * heading "the queue and the board disagree" would be false, and a reviewer who reads it twice
   * and finds nothing to decide stops reading it at all. */
  const queueRows = rows.length;
  const mirrorOnly = queueRows === 0;

  const lead = mirrorOnly
    ? `**Projection only — no queue change.** Board [#${cfg.board.number}](${cfg.board.url}) moved, but nothing that alters what the loop will build. This PR refreshes \`items[].board_status\` and \`deliverables.md\` so the in-repo status report matches the board.

${
        summary.mirrored?.length
          ? `Lane changes:\n\n${summary.mirrored.map((m) => `- \`${m.id}\`: \`${m.from ?? "—"}\` → \`${m.to ?? "—"}\``).join("\n")}`
          : "No lane changes; the regenerated table differs only in derived detail."
      }`
    : `Board [#${cfg.board.number}](${cfg.board.url}) and \`loop/state.json\` disagree about the queue. This PR makes the queue match the board, and refreshes the \`board_status\` projection and \`deliverables.md\` at the same time.

| | Item | Issue | Change | Note |
|---|---|---|---|---|
${table}`;

  return `${lead}
${reworkNote}${tierNote}${orphanNote}

${
    mirrorOnly
      ? "**Safe to merge without a decision.** Nothing here changes what the loop will build — `items[].board_status` is a read-only projection and `deliverables.md` is a status report. It goes through a PR only because `main` requires the `verify` check and admits no direct push."
      : "**Merging this is the promotion.** `loop/goal.md` is explicit that a lane queues nothing: scope is the signed inventory, queue position is `items[].status`, and a drag on the board starts no build by itself. That is deliberate — Projects v2 does not expose *who* moved a card, so a lane is not a signature. A merge is, and `git log` records the author."
  }

${
    mirrorOnly
      ? ""
      : `Every row above already has a line in the signed inventory; \`build/sync-board.mjs\` refuses to propose anything that does not. It will move an item into the queue from \`backlog\`/\`deferred\` (a first build) or from \`built\`/\`needs-human\`/\`needs-re-ref\` (a rework). It will **never** touch \`approved\`, \`handover\` or \`shipped\` — those are past the human signature, and re-opening merged work needs a new inventory row, not a lane move.

After merge, the nightly \`design-loop\` routine picks the item up on its next run.`
  }

🤖 Opened by \`.github/workflows/board-sync.yml\`
`;
}

/** Write only if the content differs by more than the sync timestamp. Returns true if written. */
function writeIfChanged(path, next) {
  const stamp = (s) =>
    s.replace(/Generated: \S+ -->/g, "Generated: — -->").replace(/"synced_at": "[^"]*"/g, '"synced_at": "—"');
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    /* new file */
  }
  if (current !== null && stamp(current) === stamp(next)) return false;
  writeFileSync(path, next);
  return true;
}

